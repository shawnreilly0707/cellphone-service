public class Cellphone {
    String serialNumber;
    String model;
    String carrier;
    String phoneNum;
    String owner;

    public Cellphone(String serialNumber,
                     String model,
                     String carrier,
                     String phoneNum,
                     String owner) {

        this.serialNumber = serialNumber;
        this.model = model;
        this.carrier = carrier;
        this.phoneNum = phoneNum;
        this.owner = owner;
    }

}
